<#
  build-app-index.ps1 -- regenerate apps/INDEX.md from apps/<id>/meta.yml.
  Usage: .\scripts\build-app-index.ps1
#>
param(
  [string]$AppsDir = (Join-Path (Split-Path $PSScriptRoot -Parent) 'apps')
)
$ErrorActionPreference = 'Stop'

function Read-Meta([string]$Path) {
  $h = @{}
  foreach ($raw in Get-Content -LiteralPath $Path) {
    $line = $raw.TrimEnd()
    if ($line -match '^\s*(#|$)') { continue }
    if ($line -match '^\s*-\s') { continue }
    if ($line -match '^([A-Za-z0-9_]+):\s*(.*)$') {
      $h[$Matches[1]] = ($Matches[2] -replace '\s+#.*$', '').Trim().Trim('"').Trim("'")
    }
  }
  return $h
}

$order = @{ active = 0; pending = 1; withdrawn = 2; rejected = 3; abandoned = 4 }
$rows = @()
foreach ($d in Get-ChildItem -LiteralPath $AppsDir -Directory | Where-Object { $_.Name -ne '_template' }) {
  $metaPath = Join-Path $d.FullName 'meta.yml'
  if (-not (Test-Path -LiteralPath $metaPath)) { continue }
  $m = Read-Meta $metaPath
  $rows += [pscustomobject]@{
    id        = $d.Name
    name      = $m['name']
    status    = $m['status']
    platforms = $m['platforms']
    tag       = $m['tag']
    upstream  = $m['upstream']
    rank      = if ($order.ContainsKey($m['status'])) { $order[$m['status']] } else { 9 }
  }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# App records (generated)')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('<!-- generated by scripts/build-app-index.ps1; do not edit by hand -->')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| id | name | status | platforms | tag | upstream | notes |')
[void]$sb.AppendLine('|---|---|---|---|---|---|---|')
foreach ($r in ($rows | Sort-Object rank, id)) {
  $name = if ($r.name) { $r.name } else { $r.id }
  [void]$sb.AppendLine("| ``$($r.id)`` | $name | $($r.status) | $($r.platforms) | $($r.tag) | $($r.upstream) | [NOTES]($($r.id)/NOTES.md) |")
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Regenerate with `scripts/build-app-index.ps1`. Status semantics: `apps/README.md`.')
$out = Join-Path $AppsDir 'INDEX.md'
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
Write-Host "wrote $out ($($rows.Count) records)"
